// =============================================================================
// DataImportService.cs
//
// Summary: Loads an export file written by DataExportService into the current
// database (either provider), preserving every primary key.
//
// Order of operations:
//   1. Scan the file (manifest, table order, "__end" marker, row counts)
//   2. Check the target: fully migrated, model fingerprint equal to the file's,
//      and empty (AspNetUsers, Projects, Builds) unless --force
//   3. In ONE transaction: delete all rows of the exported tables in reverse
//      order, insert the file's rows in batches, reset PostgreSQL identity
//      sequences, verify row counts, decrypt every project secret
//   4. Commit; any failure rolls everything back
//
// Design Decisions:
// - Compatibility uses ModelFingerprint instead of migration names: the
//   PostgreSQL migration set is one squashed InitialCreate, so the last
//   migration names differ between providers for the same schema
// - Step 3 always clears the tables, not only with --force: a freshly started
//   instance has seeded rows (the Admin/User roles) that would collide with the
//   imported keys. --force only skips the emptiness check
// - Explicit keys: SQL Server needs SET IDENTITY_INSERT ON per identity table on
//   the same connection, which the open transaction guarantees; one context is
//   used for the whole import and the change tracker is cleared per batch.
//   PostgreSQL identity columns are GENERATED BY DEFAULT and accept explicit
//   values; their sequences are moved past the maximum key afterwards
// - Builds that were Queued or Running are imported as Cancelled with no
//   Hangfire job id, because the Hangfire queue is not part of the export
// - DateTimeOffset values (Identity LockoutEnd) are normalized to offset zero;
//   Npgsql rejects non-zero offsets for timestamptz
// - Every secret is decrypted (not just one): wrong-key AES-CBC passes the
//   padding check about 1 time in 256, so a single probe is not reliable.
//   Output containing U+FFFD (invalid UTF-8) also counts as a failure
// - Store defaults: EF omits a property from the INSERT when its value equals
//   the property's sentinel (usually the CLR default) and the column has a store
//   default, so the database would write the default instead (Project
//   TimeoutMinutes 0 -> 15). SystemSettings.AllowUserRegistration is safe: EF
//   uses the store default true as its sentinel, so false is always inserted.
//   Such rows are recorded while reading and their columns are set back to the
//   exported value with one UPDATE per table and column after the table's
//   inserts, in the same transaction. Strings are not affected (their sentinel
//   is null, so "" is inserted as is); the check is generic so a future
//   HasDefaultValue is covered too
// =============================================================================

using System.Diagnostics;
using System.Security.Cryptography;
using System.Text.Json;
using Ando.Server.Data;
using Ando.Server.Models;
using Ando.Server.Services;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Storage;

namespace Ando.Server.DataPortability;

/// <summary>
/// Imports an export file into the current database.
/// </summary>
public sealed class DataImportService
{
    /// <summary>
    /// Rows per SaveChanges call.
    /// </summary>
    public const int BatchSize = 500;

    /// <summary>
    /// Error message set on builds that were Queued or Running in the export.
    /// </summary>
    public const string CancelledByImportMessage = "Cancelled by data import";

    private readonly AndoDbContext _db;
    private readonly Func<IEncryptionService> _encryptionFactory;

    /// <summary>
    /// Creates the service.
    /// </summary>
    /// <param name="db">Context of the target database.</param>
    /// <param name="encryptionFactory">
    /// Resolves the encryption service; only called when the file contains secrets, so a
    /// missing Encryption:Key does not block importing a file without secrets.
    /// </param>
    public DataImportService(AndoDbContext db, Func<IEncryptionService> encryptionFactory)
    {
        _db = db;
        _encryptionFactory = encryptionFactory;
    }

    /// <summary>
    /// Imports <paramref name="inputPath"/> into the target database.
    /// </summary>
    /// <param name="inputPath">The export file.</param>
    /// <param name="force">Delete existing data instead of refusing a non-empty target.</param>
    /// <param name="progress">Optional callback invoked when a table is done (name, rows).</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>Row counts and import statistics.</returns>
    /// <exception cref="DataPortabilityException">Thrown for operator-correctable problems; nothing is committed.</exception>
    public async Task<DataImportResult> ImportAsync(
        string inputPath,
        bool force,
        Action<string, long>? progress = null,
        CancellationToken cancellationToken = default)
    {
        var stopwatch = Stopwatch.StartNew();
        var tables = PortableTables.Resolve(_db.Model);
        var summary = await ExportFileReader.ScanAsync(inputPath, cancellationToken);
        var manifest = summary.Manifest;

        await CheckCompatibilityAsync(tables, manifest, cancellationToken);
        if (!force)
        {
            await RequireEmptyTargetAsync(cancellationToken);
        }

        IEncryptionService? encryption = null;
        if (summary.RowCounts.GetValueOrDefault("ProjectSecrets") > 0)
        {
            try
            {
                encryption = _encryptionFactory();
            }
            catch (Exception ex) when (ex is InvalidOperationException or FormatException)
            {
                throw new DataPortabilityException(
                    $"The export contains project secrets but this instance's Encryption__Key is unusable ({ex.Message}). " +
                    "Set Encryption__Key to the SAME value as on the source instance.", ex);
            }
        }

        _db.Database.SetCommandTimeout(0);
        _db.ChangeTracker.AutoDetectChangesEnabled = false;

        await using var transaction = await _db.Database.BeginTransactionAsync(cancellationToken);
        try
        {
            long deleted = 0;
            foreach (var table in tables.Reverse())
            {
                deleted += await table.DeleteAllAsync(_db, cancellationToken);
            }

            var (counts, cancelledBuilds) = await InsertRowsAsync(inputPath, tables, manifest, progress, cancellationToken);

            if (_db.Database.IsNpgsql())
            {
                await ResetPostgreSqlSequencesAsync(tables, cancellationToken);
            }

            await VerifyCountsAsync(tables, summary, cancellationToken);
            var secretsVerified = encryption == null ? 0 : await VerifySecretsAsync(encryption, cancellationToken);

            await transaction.CommitAsync(cancellationToken);

            var ordered = tables.Select(t => new KeyValuePair<string, long>(t.Name, counts.GetValueOrDefault(t.Name))).ToList();
            return new DataImportResult(manifest, ordered, deleted, cancelledBuilds, secretsVerified, stopwatch.Elapsed);
        }
        catch
        {
            await transaction.RollbackAsync(CancellationToken.None);
            throw;
        }
        finally
        {
            _db.ChangeTracker.Clear();
            _db.ChangeTracker.AutoDetectChangesEnabled = true;
        }
    }

    private async Task CheckCompatibilityAsync(
        IReadOnlyList<PortableTable> tables, ExportManifest manifest, CancellationToken cancellationToken)
    {
        var lastMigration = await DataExportService.RequireFullyMigratedAsync(_db, "Target", cancellationToken);
        var fingerprint = ModelFingerprint.Compute(tables);
        if (!string.Equals(fingerprint, manifest.ModelFingerprint, StringComparison.Ordinal))
        {
            throw new DataPortabilityException(
                "The export file's schema does not match this Ando.Server version. " +
                $"File: Ando.Server {manifest.AppVersion} ({manifest.SourceProvider}), last migration " +
                $"'{manifest.LastMigrationName}' ({manifest.LastMigration}), model fingerprint {manifest.ModelFingerprint}. " +
                $"Target: {DataExportService.GetProviderName(_db)}, last migration '{ExportManifest.MigrationName(lastMigration)}' " +
                $"({lastMigration}), model fingerprint {fingerprint}. Run the same Ando.Server version on both sides.");
        }
    }

    private async Task RequireEmptyTargetAsync(CancellationToken cancellationToken)
    {
        var users = await _db.Users.LongCountAsync(cancellationToken);
        var projects = await _db.Projects.LongCountAsync(cancellationToken);
        var builds = await _db.Builds.LongCountAsync(cancellationToken);
        if (users + projects + builds > 0)
        {
            throw new DataPortabilityException(
                $"Target database is not empty (AspNetUsers: {users}, Projects: {projects}, Builds: {builds}). " +
                "Use --force to delete all existing Ando data in the target before importing.");
        }
    }

    private async Task<(Dictionary<string, long> Counts, int CancelledBuilds)> InsertRowsAsync(
        string inputPath,
        IReadOnlyList<PortableTable> tables,
        ExportManifest manifest,
        Action<string, long>? progress,
        CancellationToken cancellationToken)
    {
        var byName = tables.ToDictionary(t => t.Name, StringComparer.Ordinal);
        var propertyMaps = tables.ToDictionary(
            t => t.Name,
            t => t.Properties.ToDictionary(p => p.Name, StringComparer.Ordinal),
            StringComparer.Ordinal);
        var defaultedProperties = tables.ToDictionary(t => t.Name, StoreDefaultProperties, StringComparer.Ordinal);
        var counts = new Dictionary<string, long>(StringComparer.Ordinal);
        var isSqlServer = _db.Database.IsSqlServer();
        var cancelledBuilds = 0;

        PortableTable? current = null;
        var pendingInBatch = 0;
        var sentinelRows = new Dictionary<IProperty, List<object>>();

        using var reader = ExportFileReader.Open(inputPath);
        await reader.ReadLineAsync(cancellationToken); // manifest
        var lineNumber = 1;

        while (await reader.ReadLineAsync(cancellationToken) is { } line)
        {
            lineNumber++;
            if (line.Length == 0)
            {
                continue;
            }

            using var document = ParseLine(line, lineNumber);
            var tableName = document.RootElement.GetProperty("table").GetString()!;
            if (tableName == ExportEndMarker.TableName)
            {
                break;
            }

            if (current?.Name != tableName)
            {
                if (current != null)
                {
                    await EndTableAsync(current, isSqlServer, counts, sentinelRows, progress, cancellationToken);
                }

                current = byName[tableName];
                pendingInBatch = 0;
                sentinelRows.Clear();
                counts[current.Name] = 0;
                if (isSqlServer && current.IdentityKey != null)
                {
                    await SetIdentityInsertAsync(current, on: true, cancellationToken);
                }
            }

            if (!document.RootElement.TryGetProperty("row", out var row) || row.ValueKind != JsonValueKind.Object)
            {
                throw new DataPortabilityException($"Line {lineNumber}: missing \"row\" object.");
            }

            var entity = CreateEntity(current, propertyMaps[current.Name], row, lineNumber);
            if (entity is Build build && build.Status is BuildStatus.Queued or BuildStatus.Running)
            {
                build.Status = BuildStatus.Cancelled;
                build.HangfireJobId = null;
                build.ErrorMessage = CancelledByImportMessage;
                build.FinishedAt ??= manifest.ExportedAtUtc;
                cancelledBuilds++;
            }

            RecordSentinelValues(current, defaultedProperties[current.Name], entity, sentinelRows);
            _db.Add(entity);
            counts[current.Name]++;
            if (++pendingInBatch >= BatchSize)
            {
                await SaveBatchAsync(current, lineNumber, cancellationToken);
                pendingInBatch = 0;
            }
        }

        if (current != null)
        {
            await EndTableAsync(current, isSqlServer, counts, sentinelRows, progress, cancellationToken);
        }

        return (counts, cancelledBuilds);
    }

    private async Task EndTableAsync(
        PortableTable table,
        bool isSqlServer,
        Dictionary<string, long> counts,
        IReadOnlyDictionary<IProperty, List<object>> sentinelRows,
        Action<string, long>? progress,
        CancellationToken cancellationToken)
    {
        await SaveBatchAsync(table, null, cancellationToken);
        if (isSqlServer && table.IdentityKey != null)
        {
            await SetIdentityInsertAsync(table, on: false, cancellationToken);
        }

        await RestoreSentinelValuesAsync(table, sentinelRows, cancellationToken);

        progress?.Invoke(table.Name, counts[table.Name]);
    }

    private async Task SaveBatchAsync(PortableTable table, int? lineNumber, CancellationToken cancellationToken)
    {
        try
        {
            await _db.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateException ex)
        {
            var where = lineNumber.HasValue ? $" (batch ending at line {lineNumber})" : "";
            throw new DataPortabilityException(
                $"Inserting rows into {table.Name} failed{where}: {ex.InnerException?.Message ?? ex.Message}", ex);
        }

        _db.ChangeTracker.Clear();
    }

    /// <summary>
    /// Returns the non-key properties whose column has a store default (HasDefaultValue or
    /// HasDefaultValueSql). EF does not insert a sentinel value for these. Uses the annotations
    /// because GetDefaultValue() also returns the CLR default for unconfigured value types.
    /// </summary>
    /// <param name="table">The table.</param>
    /// <returns>The properties, possibly empty.</returns>
    internal static IReadOnlyList<IProperty> StoreDefaultProperties(PortableTable table) =>
        table.Properties
            .Where(p => !p.IsPrimaryKey()
                && (p.FindAnnotation(RelationalAnnotationNames.DefaultValue) != null
                    || p.FindAnnotation(RelationalAnnotationNames.DefaultValueSql) != null))
            .ToList();

    private static void RecordSentinelValues(
        PortableTable table,
        IReadOnlyList<IProperty> defaultedProperties,
        object entity,
        Dictionary<IProperty, List<object>> sentinelRows)
    {
        foreach (var property in defaultedProperties)
        {
            if (!Equals(property.PropertyInfo!.GetValue(entity), property.Sentinel))
            {
                continue;
            }

            var key = table.EntityType.FindPrimaryKey()!.Properties;
            if (key.Count != 1)
            {
                throw new InvalidOperationException(
                    $"{table.Name}.{property.Name} has a store default but {table.Name} has a composite key; restoring sentinel values is not supported.");
            }

            if (!sentinelRows.TryGetValue(property, out var keys))
            {
                sentinelRows[property] = keys = [];
            }

            keys.Add(key[0].PropertyInfo!.GetValue(entity)!);
        }
    }

    /// <summary>
    /// Sets columns that the database filled with its store default back to the exported
    /// sentinel value (e.g. TimeoutMinutes 0 instead of 15).
    /// </summary>
    private async Task RestoreSentinelValuesAsync(
        PortableTable table, IReadOnlyDictionary<IProperty, List<object>> sentinelRows, CancellationToken cancellationToken)
    {
        if (sentinelRows.Count == 0)
        {
            return;
        }

        var helper = _db.GetService<ISqlGenerationHelper>();
        var qualified = QualifiedName(table);
        var keyColumn = helper.DelimitIdentifier(table.EntityType.FindPrimaryKey()!.Properties[0].GetColumnName());
        foreach (var (property, keys) in sentinelRows)
        {
            var column = helper.DelimitIdentifier(property.GetColumnName());
            var sentinel = property.Sentinel;
            var converter = property.GetTypeMapping().Converter;
            var value = sentinel == null ? null : converter?.ConvertToProvider(sentinel) ?? sentinel;

            foreach (var chunk in keys.Chunk(BatchSize))
            {
                var parameters = new List<object>();
                string assignment;
                if (value == null)
                {
                    assignment = "NULL";
                }
                else
                {
                    assignment = "{0}";
                    parameters.Add(value);
                }

                var placeholders = new List<string>(chunk.Length);
                foreach (var key in chunk)
                {
                    placeholders.Add($"{{{parameters.Count}}}");
                    parameters.Add(key);
                }

                var sql = $"UPDATE {qualified} SET {column} = {assignment} WHERE {keyColumn} IN ({string.Join(", ", placeholders)})";
                await _db.Database.ExecuteSqlRawAsync(sql, parameters, cancellationToken);
            }
        }
    }

    private static JsonDocument ParseLine(string line, int lineNumber)
    {
        try
        {
            return JsonDocument.Parse(line);
        }
        catch (JsonException ex)
        {
            throw new DataPortabilityException($"Line {lineNumber}: invalid JSON ({ex.Message}).", ex);
        }
    }

    /// <summary>
    /// Materializes an entity from a row object; every mapped column must be present exactly.
    /// </summary>
    /// <param name="table">Target table.</param>
    /// <param name="properties">The table's properties by name.</param>
    /// <param name="row">The "row" JSON object.</param>
    /// <param name="lineNumber">1-based line number for messages.</param>
    /// <returns>The entity, not yet tracked.</returns>
    internal static object CreateEntity(
        PortableTable table, IReadOnlyDictionary<string, IProperty> properties, JsonElement row, int lineNumber)
    {
        var entity = Activator.CreateInstance(table.ClrType)
            ?? throw new InvalidOperationException($"Cannot create {table.ClrType.Name}.");
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var member in row.EnumerateObject())
        {
            if (!properties.TryGetValue(member.Name, out var property))
            {
                throw new DataPortabilityException($"Line {lineNumber}: unknown column {table.Name}.{member.Name}.");
            }

            object? value;
            try
            {
                value = PortableValueSerializer.Read(member.Value, property.ClrType);
            }
            catch (FormatException ex)
            {
                throw new DataPortabilityException($"Line {lineNumber}: invalid value for {table.Name}.{property.Name}: {ex.Message}", ex);
            }

            if (value is DateTimeOffset offset)
            {
                value = offset.ToUniversalTime();
            }

            property.PropertyInfo!.SetValue(entity, value);
            seen.Add(member.Name);
        }

        if (seen.Count != properties.Count)
        {
            var missing = properties.Keys.Where(k => !seen.Contains(k));
            throw new DataPortabilityException(
                $"Line {lineNumber}: {table.Name} row is missing columns {string.Join(", ", missing)}.");
        }

        return entity;
    }

    private async Task SetIdentityInsertAsync(PortableTable table, bool on, CancellationToken cancellationToken)
    {
        var sql = $"SET IDENTITY_INSERT {QualifiedName(table)} {(on ? "ON" : "OFF")}";
        await _db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
    }

    private async Task ResetPostgreSqlSequencesAsync(IReadOnlyList<PortableTable> tables, CancellationToken cancellationToken)
    {
        var helper = _db.GetService<ISqlGenerationHelper>();
        foreach (var table in tables.Where(t => t.IdentityKey != null))
        {
            var qualified = QualifiedName(table);
            var columnName = table.IdentityKey!.GetColumnName();
            var column = helper.DelimitIdentifier(columnName);
            var tableLiteral = qualified.Replace("'", "''");
            var columnLiteral = columnName.Replace("'", "''");
            // Empty table: setval(seq, 1, false) so the next value is 1.
            var sql =
                $"SELECT setval(pg_get_serial_sequence('{tableLiteral}', '{columnLiteral}'), " +
                $"COALESCE((SELECT MAX({column}) FROM {qualified}), 1), " +
                $"(SELECT MAX({column}) FROM {qualified}) IS NOT NULL)";
            await _db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
        }
    }

    private string QualifiedName(PortableTable table) =>
        _db.GetService<ISqlGenerationHelper>().DelimitIdentifier(table.Name, table.EntityType.GetSchema());

    private async Task VerifyCountsAsync(
        IReadOnlyList<PortableTable> tables, ExportFileSummary summary, CancellationToken cancellationToken)
    {
        foreach (var table in tables)
        {
            var actual = await table.CountAsync(_db, cancellationToken);
            var expected = summary.RowCounts.GetValueOrDefault(table.Name);
            if (actual != expected)
            {
                throw new DataPortabilityException(
                    $"Row count check failed for {table.Name}: the file has {expected} rows but the database has {actual} after import.");
            }
        }
    }

    private async Task<int> VerifySecretsAsync(IEncryptionService encryption, CancellationToken cancellationToken)
    {
        var secrets = await _db.ProjectSecrets.AsNoTracking()
            .OrderBy(s => s.Id)
            .Select(s => new { s.Id, s.ProjectId, s.Name, s.EncryptedValue })
            .ToListAsync(cancellationToken);

        var failed = secrets.Where(s => !CanDecrypt(encryption, s.EncryptedValue)).ToList();
        if (failed.Count > 0)
        {
            var first = failed[0];
            throw new DataPortabilityException(
                $"{failed.Count} of {secrets.Count} project secrets cannot be decrypted with this instance's Encryption__Key " +
                $"(first: project {first.ProjectId}, secret '{first.Name}'). The target's Encryption__Key differs from the " +
                "source's. Set it to the source value and import again. Nothing was imported.");
        }

        return secrets.Count;
    }

    private static bool CanDecrypt(IEncryptionService encryption, string cipherText)
    {
        try
        {
            return !encryption.Decrypt(cipherText).Contains('�');
        }
        catch (Exception ex) when (ex is CryptographicException or FormatException or ArgumentException)
        {
            return false;
        }
    }
}
